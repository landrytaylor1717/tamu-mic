// Methodology (documented here since this is a derived series, not a raw
// disclosed number like spyDailyCloses):
//   1. For each of the fund's 11 positions with fully self-consistent data
//      in the source sheet (current shares/avg price/cost basis/purchase
//      date all agree with each other), compute that stock's own real
//      return since ITS OWN purchase date using real daily closes.
//   2. Blend those returns each day, weighted by each position's current
//      disclosed %-of-AUM weight (renormalized among whichever positions
//      have actually been purchased by that date), producing a real,
//      price-driven curve shape — rallies, drawdowns, and the Apr 2026
//      selloff all show up because they're real market moves in real
//      holdings, not smoothed.
//   3. That raw blended curve is then calibrated (two line segments,
//      split at the Jan 1 2026 rebalance date) so it lands exactly on the
//      fund's own two disclosed authoritative return figures — 31.27%
//      since inception, 7.30% year-to-date — rather than trusting a
//      bottom-up dollar reconstruction, which isn't fully determined by
//      the sheet: several rows in the sheet's Jan-2026 rebalance-planning
//      table contradict the current holdings table (e.g. it shows AAAU
//      sold to a 0% weight, but AAAU is still a live 2.20%-weight holding
//      today; Netflix's own purchase date directly contradicts its row in
//      that same table), so it reads as an unexecuted planning worksheet
//      rather than a reliable transaction log, and isn't used here.
//   4. The 5 newest positions (Intuit, NRG, AVAV, DraftKings, S&P Global)
//      aren't in this blend yet, same reason they're absent from
//      lib/portfolioData.js — no confirmed share count/cost basis to
//      compute a real return from.
//
// The visible jump on 2025-12-02 is real, not a bug: three new positions
// (Mastercard, Adobe, Meta) enter the blend that day at their own 0%
